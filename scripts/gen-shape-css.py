#!/usr/bin/env python3
"""Generate the uniform-corner overrides for GTK3, GTK4/libadwaita and GNOME Shell.

Reads the stock stylesheets installed on this machine and re-emits every rule
that sets a corner radius, same selector and order, with the radius replaced by
RADIUS. Circles and tracks (radios, switches, sliders, avatars, icon buttons)
keep their stock shape. Re-run after libadwaita, GTK or Yaru upgrades:

    scripts/gen-shape-css.py && chezmoi apply
"""
import re
import subprocess
from pathlib import Path

RADIUS = 6  # px, everywhere
HOME = Path(__file__).resolve().parent.parent / "home"
LIB = "/usr/lib/x86_64-linux-gnu"

# Selectors that stay as the toolkit draws them.
GTK_ROUND = re.compile(
    r"circular|avatar|radio|switch|slider|scale|progress|levelbar|scrollbar|indicator"
    r"|drag-handle|windowcontrols|\.close|cursor-handle|sidebar-button|titlebutton"
    r"|selection-mode|image-button|tabthumbnail button|colorswatch|adaptive-preview"
    r"|\bcheck\b|video ")
SHELL_ROUND = re.compile(
    r"icon-button|login-dialog-button|show-pointer-button|toggle-switch|handle|calendar-day\b"
    r"|close-button|expand-button|collapse-button|pager-button|message-icon|capture-button|selector-check|workspace-dot"
    r"|\.header \.icon|window-close|page-indicator|system-action-icon|page-navigation-arrow"
    r"|user-icon|notification-count|notification-badge|slider|check-box|running-dot|ripple"
    r"|spinner|keyboard|StScrollBar|dashtodock|LookingGlass")

DECL = re.compile(r"(border(?:-[a-z]+)*-radius)\s*:\s*([^;}]+)")


def gresource(lib, path):
    return subprocess.run(["gresource", "extract", f"{LIB}/{lib}", path],
                          check=True, capture_output=True, text=True).stdout


def split_selectors(sel):
    parts, depth, cur = [], 0, ""
    for ch in sel:
        depth += ch == "("
        depth -= ch == ")"
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [" ".join(p.split()) for p in parts if p.strip()]


def new_value(value):
    def px(m):
        return f"{RADIUS}px" if float(m.group(1)) > RADIUS else m.group(0)
    value = re.sub(r"(\d+(?:\.\d+)?)px", px, value)
    return re.sub(r"\b(?:50|100)%", f"{RADIUS}px", value)


def blocks(css):
    """Yield (prelude, body) for each top-level block, braces balanced."""
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            return
        depth, k = 1, j + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        prelude = css[i:j].rsplit(";", 1)[-1].strip()
        yield prelude, css[j + 1:k - 1]
        i = k


def convert(css, keep, indent=""):
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith("@"):
            if prelude.startswith("@media"):
                inner = convert(body, keep, indent + "  ")
                if inner:
                    out.append(f"{indent}{prelude} {{\n{inner}\n{indent}}}")
            continue
        found = [(prop, value.strip()) for prop, value in DECL.findall(body)]
        if not found:
            continue
        # Every radius rule is re-emitted, changed or not: this sheet outranks
        # the stock one, so a rule left out would lose to a broader one here.
        selectors = split_selectors(prelude)
        for group, change in (([s for s in selectors if not keep.search(s)], True),
                              ([s for s in selectors if keep.search(s)], False)):
            if group:
                decls = " ".join(f"{p}: {new_value(v) if change else v};" for p, v in found)
                out.append(f"{indent}{', '.join(group)} {{ {decls} }}")
    return "\n".join(out)


def strip(css):
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def write(rel, text):
    path = HOME / rel
    path.write_text(text + "\n")
    print(f"{rel}: {text.count(chr(10)) + 1} lines")


HEAD = (f"/* Generated by scripts/gen-shape-css.py: every corner {RADIUS}px, "
        "circles and tracks left alone. Do not edit. */\n")

gtk3 = strip(gresource("libgtk-3.so.0", "/org/gtk/libgtk/theme/Adwaita/gtk-contained.css"))
write("private_dot_config/gtk-3.0/gtk.css", HEAD + convert(gtk3, GTK_ROUND))

adw = strip(gresource("libadwaita-1.so.0", "/org/gnome/Adwaita/styles/default-light-yaru-blue.css"))
write("private_dot_config/gtk-4.0/shape.css",
      HEAD + f":root {{ --window-radius: {RADIUS}px; }}\n" + convert(adw, GTK_ROUND))

shell = convert(strip(Path("/usr/share/gnome-shell/theme/Yaru/gnome-shell.css").read_text()), SHELL_ROUND)
for variant in ("Light", "Dark"):
    write(f"dot_themes/Bauhaus-{variant}/gnome-shell/shape.css", HEAD + shell)
